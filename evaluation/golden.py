class GoldenDatasetBuilder:
    """Load, query, and persist the golden QA dataset.

    Args:
        items: Optional pre-loaded list of :class:`~evaluation.schemas.GoldenQAItem`.
               If not supplied, use :meth:`load_from_seed` or :meth:`load_from_file`.
    """

    def __init__(self, items: list[GoldenQAItem] | None = None) -> None:
        self._items: list[GoldenQAItem] = items or []

    # ------------------------------------------------------------------
    # Loading
    # ------------------------------------------------------------------

    def load_from_seed(self) -> list[GoldenQAItem]:
        """Deserialise and return :data:`GOLDEN_QA_SEED` as typed models.

        Returns:
            List of 40 :class:`~evaluation.schemas.GoldenQAItem` from the seed.
        """
        self._items = [GoldenQAItem.model_validate(d) for d in GOLDEN_QA_SEED]
        logger.info("golden_qa_loaded_from_seed", count=len(self._items))
        return self._items

    def load_from_file(self, path: str | Path) -> list[GoldenQAItem]:
        """Load golden QA items from a JSONL file.

        Args:
            path: Path to a JSONL file where each line is a :class:`~evaluation.schemas.GoldenQAItem`.

        Returns:
            Loaded and validated items.

        Raises:
            FileNotFoundError: If the file does not exist.
            ValueError: If a line fails Pydantic validation.
        """
        resolved = Path(path)
        if not resolved.exists():
            raise FileNotFoundError(str(resolved))
        items: list[GoldenQAItem] = []
        with resolved.open(encoding="utf-8") as fh:
            for raw in fh:
                stripped = raw.strip()
                if stripped:
                    items.append(GoldenQAItem.model_validate_json(stripped))
        self._items = items
        logger.info("golden_qa_loaded_from_file", path=str(resolved), count=len(items))
        return items

    def write_to_file(self, path: str | Path, items: list[GoldenQAItem] | None = None) -> None:
        """Write golden QA items to a JSONL file.

        Args:
            path: Destination path (parent directories will be created).
            items: Items to write; defaults to the currently loaded items.
        """
        records = items if items is not None else self._items
        dest = Path(path)
        dest.parent.mkdir(parents=True, exist_ok=True)
        with dest.open("w", encoding="utf-8") as fh:
            for item in records:
                fh.write(item.model_dump_json() + "\n")
        logger.info("golden_qa_written", path=str(dest), count=len(records))

    # ------------------------------------------------------------------
    # Queries
    # ------------------------------------------------------------------

    @property
    def items(self) -> list[GoldenQAItem]:
        """All currently loaded golden QA items."""
        return list(self._items)

    def get_by_id(self, question_id: str) -> GoldenQAItem | None:
        """Return the item with ``question_id``, or ``None`` if not found.

        Args:
            question_id: Identifier matching :attr:`~evaluation.schemas.GoldenQAItem.question_id`.

        Returns:
            Matching :class:`~evaluation.schemas.GoldenQAItem` or ``None``.
        """
        for item in self._items:
            if item.question_id == question_id:
                return item
        return None

    def get_by_failure_mode(self, mode: str) -> list[GoldenQAItem]:
        """Return all items with a specific failure mode.

        Args:
            mode: Value from :class:`~schemas.models.FailureMode` (e.g. ``"chunking_boundary"``).

        Returns:
            Filtered list of :class:`~evaluation.schemas.GoldenQAItem`.
        """
        return [i for i in self._items if i.failure_mode == mode]

    def get_by_difficulty(self, difficulty: str) -> list[GoldenQAItem]:
        """Return all items with a specific difficulty level.

        Args:
            difficulty: Value from :class:`~evaluation.schemas.Difficulty`.

        Returns:
            Filtered list of :class:`~evaluation.schemas.GoldenQAItem`.
        """
        return [i for i in self._items if i.difficulty == difficulty]

    def get_by_domain(self, domain: str) -> list[GoldenQAItem]:
        """Return all items in a specific domain.

        Args:
            domain: Domain string (e.g. ``"safety"``, ``"geology"``).

        Returns:
            Filtered list of :class:`~evaluation.schemas.GoldenQAItem`.
        """
        return [i for i in self._items if i.domain == domain]

    def get_hallucination_cases(self) -> list[GoldenQAItem]:
        """Return all items with ``failure_mode == 'hallucination'``.

        Returns:
            Items designed to test hallucination detection.
        """
        return self.get_by_failure_mode("hallucination")

    def get_temporal_cases(self) -> list[GoldenQAItem]:
        """Return all items with ``failure_mode == 'temporal_confusion'``.

        Returns:
            Items designed to test temporal validity filtering.
        """
        return self.get_by_failure_mode("temporal_confusion")
